export function randomWord(exclude?: string): string {
  let word = WORD_BANK[Math.floor(Math.random() * WORD_BANK.length)]
  while (word === exclude) {
    word = WORD_BANK[Math.floor(Math.random() * WORD_BANK.length)]
  }
  return word
}
